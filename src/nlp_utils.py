def detect_doc_type(text: str) -> str:
    """
    Примитивное, но расширенное определение типа меддокумента по ключевым словам.
    Работает эвристически, чисто для подсказки ИИ.
    """
    t = (text or "").lower()

    # Анализ крови (общий/биохимия)
    if any(w in t for w in [
        "эритроцит", "гемоглобин", "гематокрит", "лейкоцит", "тромбоцит",
        "rbc", "wbc", "plt", "соэ", "сое",
        "аст", "алт", "ggt", "ggtp", "билирубин", "креатинин",
        "мочевина", "общий белок", "альбумин", "липидный профиль",
        "огк", "общий анализ крови"
    ]):
        return "анализ крови"

    # Анализ мочи
    if any(w in t for w in [
        "моча", "общий анализ мочи", "урина",
        "leu/ul", "ery/ul", "лейкоциты в моче", "эритроциты в моче",
        "u-protein", "u-glucose", "цилиндры", "эпителий мочевого",
        "микрогематурия", "гематурия"
    ]):
        return "анализ мочи"

    # Гормоны / эндокринология
    if any(w in t for w in [
        "ттг", "т4", "т3", "т4 свободный", "инсулин", "hba1c",
        "глюкоза крови", "кортизол", "пролактин", "эстрадиол",
        "тестостерон"
    ]):
        return "гормональный анализ / эндокринология"

    # Коагулограмма
    if any(w in t for w in [
        "коагулограмма", "мно", "инр", "фибриноген", "аптт", "протромбиновое время"
    ]):
        return "коагулограмма (свёртываемость крови)"

    # Онкомаркеры
    if any(w in t for w in [
        "са-125", "са-19-9", "са 19-9", "са 125", "са-15-3", "са 15-3",
        "psa", "пса", "онкомаркер"
    ]):
        return "анализ на онкомаркеры"

    # УЗИ
    if any(w in t for w in [
        "узи", "эхоструктура", "эхопризнаки", "эхогенность", "сонография"
    ]):
        return "узи / сонография"

    # МРТ
    if any(w in t for w in [
        "мрт", "магнитно-резонансная томография"
    ]):
        return "мрт"

    # КТ
    if any(w in t for w in [
        "кт ", "компьютерная томография"
    ]):
        return "кт"

    # ЭКГ
    if any(w in t for w in [
        "экг", "электрокардиограмма", "pq", "qt", "qrs", "синусовый ритм"
    ]):
        return "экг"

    # Выписка / эпикриз / заключение
    if any(w in t for w in [
        "выписка", "эпикриз", "заключение", "анамнез", "жалобы",
        "рекомендации", "осмотр", "диагноз"
    ]):
        return "выписка / заключение"

    # По умолчанию
    return "неопределённый тип меддокумента"


def detect_user_emotion(text: str) -> str:
    """
    Грубая оценка эмоционального оттенка сообщения:
    'panic', 'anxious', 'sad', 'joking', 'angry', 'neutral'
    """
    t = (text or "").lower()

    panic_words = [
        "паника", "очень страшно", "мне страшно", "я боюсь",
        "это ужас", "кошмар", "я в шоке"
    ]
    anxious_words = [
        "волнуюсь", "переживаю", "тревожно", "боюсь результата",
        "очень переживаю", "нормально ли это"
    ]
    sad_words = [
        "грустно", "плохо на душе", "депрессия", "нет сил", "плакать хочется"
    ]
    joke_words = [
        "шутка", "лол", "ахах", "ахаха", "😀", "😅", "😂"
    ]
    angry_words = [
        "ненавижу", "вы что издеваетесь", "идиот", "дебил", "бред", "фигня"
    ]

    if any(w in t for w in panic_words):
        return "panic"
    if any(w in t for w in anxious_words):
        return "anxious"
    if any(w in t for w in sad_words):
        return "sad"
    if any(w in t for w in joke_words):
        return "joking"
    if any(w in t for w in angry_words):
        return "angry"

    return "neutral"


def detect_red_flags(text: str) -> List[str]:
    """
    Ищем возможные 'красные флажки' исключительно по формулировкам
    (без жёсткого медицинского вывода).
    Это не диагноз, а подсказка ИИ, что стоит быть аккуратнее в комментариях.
    """
    t = (text or "").lower()
    flags: List[str] = []

    # Гематурия / кровь в моче
    if any(w in t for w in ["гематурия", "микрогематурия", "кровь в моче"]):
        flags.append("возможная кровь в моче / гематурия")

    # Очень высокие/низкие значения в тексте (словесно)
    if any(w in t for w in ["значительно повышен", "резко повышен", "резко снижен", "значительно снижен"]):
        flags.append("в тексте упоминаются выраженные отклонения показателей")

    # Сахар / глюкоза
    if "глюкоза" in t or "сахар крови" in t:
        if any(w in t for w in ["очень высокий", "значительно выше", "выше нормы", "выраженное повышение"]):
            flags.append("может быть значимое повышение сахара")

    # Воспаление / высокий CRP, лейкоцитоз (словесно)
    if any(w in t for w in ["лейкоцитоз", "высокие лейкоциты", "повышенные лейкоциты", "высокий crp", "повышенный crp"]):
        flags.append("признаки возможного воспалительного процесса по тексту")

    # Сильно низкий гемоглобин (словами)
    if any(w in t for w in ["тяжелая анемия", "выраженная анемия", "низкий гемоглобин"]):
        flags.append("признаки возможной выраженной анемии по тексту")

    # Боль, температура - как подсказка, что человек может быть симптомным
    if any(w in t for w in ["сильная боль", "очень больно", "высокая температура", "держится температура"]):
        flags.append("описаны выраженные симптомы (боль/температура)")

    return flags


def build_ai_input(
    raw_text: str,
    doc_type: Optional[str] = None,
    user_role: Optional[str] = None,
    emotion: Optional[str] = None,
    flags: Optional[List[str]] = None,
) -> str:
    """
    Собираем контекст для ИИ: что за документ, кто пользователь, какой эмоциональный фон
    и есть ли возможные значимые моменты по тексту.
    """
    doc_type = doc_type or "неопределённый тип меддокумента"
    flags = flags or []

    header_lines = []

    if user_role:
        header_lines.append(f"Роль пользователя (примерно): {user_role}.")

    header_lines.append(f"Предполагаемый тип документа: {doc_type}.")

    if emotion and emotion != "neutral":
        header_lines.append(
            f"Эмоциональное состояние пользователя по тексту: {emotion} "
            f"(отвечай особенно бережно и понятно)."
        )

    if flags:
        flags_str = "; ".join(flags)
        header_lines.append(
            "Внимание: в тексте обнаружены возможные значимые моменты "
            f"(это не диагноз, но стоит быть аккуратнее в комментариях): {flags_str}."
        )

    header_lines.append(
        "Ниже приведён текст документа или вопрос пользователя. "
        "Проанализируй его и объясни понятным языком, соблюдая правила безопасности."
    )

    header = "\n".join(header_lines)
    return f"{header}\n\n{raw_text}"